    <h2>Wireframe &amp; layout</h2>
    <p>
        Nedenfor ses det foreslåede layout for startsiden. Designet udnytter hele skærmbredden og
        holder de vigtigste informationer "above the fold". Yderligere detaljer scroller i sektioner.
    </p>
    <div class="wireframe-grid">
        <div class="wireframe-column">
            <h3>Top (Header + Navigation)</h3>
            <ul>
                <li>Hero-tekst med fokus på AD-DS og GF2 målgruppen.</li>
                <li>Primær navigation med hurtige ankre til framework, wireframe, læringsrejse osv.</li>
                <li>Call-to-action: "Start modul" og "Gå til simulering" (tilføjes i næste iteration).</li>
            </ul>
        </div>
        <div class="wireframe-column">
            <h3>Midte (Indholdszoner)</h3>
            <ul>
                <li>Section cards der visualiserer læringsflowet.</li>
                <li>Karussel eller tabs til modulvisning (reserveret plads).</li>
                <li>To-spaltet layout på store skærme, enkelt spalte på mobil.</li>
            </ul>
        </div>
        <div class="wireframe-column">
            <h3>Bund (Support &amp; Ressourcer)</h3>
            <ul>
                <li>Links til lærervejledninger, evalueringsskemaer og elevmaterialer.</li>
                <li>Supportkort med ChatGPT assistent og FAQ.</li>
                <li>Footer med licensinformation og kontakt.</li>
            </ul>
        </div>
    </div>
    <p class="wireframe-note">
        Wireframen beskriver første iteration. De specifikke modulkomponenter, simuleringer og
        opgavebank integreres i dedikerede filer, så kodebasen forbliver modulær.
    </p>
