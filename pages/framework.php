    <h2>Pædagogisk framework</h2>
    <p>
        Frameworket kombinerer korte læringsloops med praksisnære øvelser om Windows Server AD-DS,
        OU-strukturer og GPO-administration. Hvert modul følger rytmen <strong>Lær → Prøv → Reflektér → Anvend</strong>.
    </p>
    <div class="grid">
        <div class="card">
            <h3>Lær</h3>
            <ul>
                <li>Interaktive mikro-moduler med videoer, artikler og live-demoer.</li>
                <li>Begrebsforklaringer på dansk med fokus på GF2 elevers forudsætninger.</li>
                <li>Inline ordforklaringer og visualiseringer af AD-DS topologier.</li>
            </ul>
        </div>
        <div class="card">
            <h3>Prøv (Simuleringer)</h3>
            <ul>
                <li>Browserbaserede scenarier hvor eleverne kan konfigurere OU-strukturer og GPO'er.</li>
                <li>Guidede "sandbox"-miljøer med trin-for-trin prompts og feedback.</li>
                <li>Automatiske checkpoints der verificerer forståelse før næste niveau.</li>
            </ul>
        </div>
        <div class="card">
            <h3>Reallife</h3>
            <ul>
                <li>Workshops med fysisk eller virtuel Windows Server instans.</li>
                <li>Rollespil: elevteam agerer virksomhedens it-afdeling med konkrete krav.</li>
                <li>Dokumentationsopgave hvor eleverne skriver GPO-ændringslog.</li>
            </ul>
        </div>
        <div class="card">
            <h3>Evaluering &amp; Feedback</h3>
            <ul>
                <li>Digitale refleksionskort efter hver aktivitet.</li>
                <li>Summative opgaver der kombinerer simulering og fysisk opsætning.</li>
                <li>Auto-genererede rapporter til undervisere med elevprogression.</li>
            </ul>
        </div>
    </div>
    <p>
        Alle elementer designes til klasseundervisning, gruppeforløb og individuelle fordybelser.
        Undervisere kan aktivere/deaktivere moduler alt efter klassens behov.
    </p>
</article>
