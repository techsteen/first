    <h2>AD-DS læringslaboratoriet</h2>
    <p>
        Velkommen til dit praksisnære træningsforløb i Windows Server Active Directory Domain Services.
        Hele undervisningen er bygget som et laboratorieforløb, hvor du lærer ved at gøre.
        Hvert afsnit starter med en kort forklaring og går derefter direkte over i en simulering,
        hvor du gennemfører kommandoer, bygger OU-strukturer og tester gruppepolitikker uden at forlade siden.
    </p>
    <p>
        I venstremenuen kan du hoppe mellem de tre hovedemner: <strong>Domæne og controller</strong>,
        <strong>OU-design</strong> og <strong>GPO-politikker</strong>. Brug de indbyggede checklister til at markere din progression,
        og klik på de små spørgsmålstegn hvis du vil have ChatGPT til at forklare et trin.
    </p>
    <div class="learning-modes">
        <section>
            <h3>Du lærer ved</h3>
            <ul>
                <li>At følge guidede scripts og se resultatet i en simuleret konsol.</li>
                <li>At bygge organisationstræet selv og opleve, hvordan bruger- og enhedspolitikker påvirkes.</li>
                <li>At løse praksisopgaver, hvor du kobler viden fra laboratoriet til skolens miljø.</li>
            </ul>
        </section>
        <section>
            <h3>Sådan bruger du hjælpen</h3>
            <ul>
                <li>Marker tekst i forløbet og tryk på <em>Forklar</em> for at få en uddybning.</li>
                <li>Tryk på spørgsmålstegn ved svære trin – de sender et præformuleret spørgsmål til ChatGPT API'et.</li>
                <li>Opsummer dine beslutninger i refleksionerne, så underviseren kan give feedback.</li>
            </ul>
        </section>
    </div>
